/**
 * Ступень каскада разгадывания капчи.
 *
 * Порядок ступеней задаётся массивом в registry.ts — добавить или переставить
 * решатель стоит одну строку. Клиент про ступени ничего не знает: он шлёт
 * картинку и получает строку.
 */
export interface CaptchaSolver {
  name: string;

  /** Доступен ли решатель в текущей конфигурации (заданы ли ключи). */
  isAvailable(): boolean;

  /**
   * Попытка прочитать капчу.
   *
   * Возвращает строку-ответ или null, если решатель не справился.
   * Человеческая ступень возвращает Promise, который резолвится, когда придёт
   * ответ из Telegram, — поэтому решение задачи асинхронно по своей природе.
   */
  solve(input: SolveInput): Promise<string | null>;
}

export interface SolveInput {
  taskId: string;
  /** Картинка капчи в base64 (без префикса data:). */
  image: string;
  /** Что именно нужно прочитать: «5 символов, латиница и цифры». */
  hint: string | null;
  /** Кто просит и зачем — попадает в подпись сообщения человеку. */
  context: string | null;
  /** Сколько осталось до истечения срока задачи. */
  timeoutMs: number;
}
